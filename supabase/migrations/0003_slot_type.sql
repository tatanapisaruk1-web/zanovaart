-- ЗАНОВО — тип слота (групповой / индивидуальный)
--
-- В старой панели при создании слота всегда указывался тип — групповой
-- или индивидуальный. Добавляем это поле на слот: оно не заменяет
-- мультитиповость (несколько видов МК в одном слоте через slot_offerings),
-- а просто описывает формат проведения этого слота целиком.

alter table slots
  add column type text not null default 'group'
  check (type in ('group', 'individual'));
